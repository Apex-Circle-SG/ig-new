import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repository = fileURLToPath(new URL('../', import.meta.url));
const generated = path.join(repository, 'apps/web/src/generated');
await mkdir(generated, { recursive: true });
const serverPath = path.join(generated, '.income-render.cjs');
const common = {
  absWorkingDir: repository,
  bundle: true,
  minify: true,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
};
const [browser] = await Promise.all([
  build({
    ...common,
    entryPoints: ['apps/web/src/embed/client.tsx'],
    platform: 'browser',
    format: 'iife',
    target: ['es2022'],
    write: false,
  }),
  build({
    ...common,
    entryPoints: ['apps/web/src/embed/render.tsx'],
    platform: 'node',
    format: 'cjs',
    outfile: serverPath,
  }),
]);
try {
  const { renderIncomeEmbed } = createRequire(import.meta.url)(serverPath);
  const css = await readFile(path.join(repository, 'apps/web/src/app/globals.css'), 'utf8');
  // This document must remain self-contained even if global styles later gain hosted fonts.
  const localCss = css
    .replace(/@import\s+(?:url\([^)]*\)|[^;]+);/gi, '')
    .replace(/@font-face\s*\{[^}]*\}/gi, '')
    .replace(/url\([^)]*\)/gi, 'none')
    .replace(/<\/style/gi, '<\\/style');
  const javascript = browser.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  const documentFor = (compact) => `<!doctype html>
<html lang="en-US" data-view="${compact ? 'compact' : 'full'}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow">
<meta name="referrer" content="no-referrer">
<title>Private income percentile calculator | InsightGinie</title>
<style>${localCss}
html { scroll-behavior: auto; scroll-padding-top: 0; }
body { background: transparent; }
#income-embed-root { display: flow-root; padding: 6px; width: 100%; }
.mini-tool { transform: none; box-shadow: none; }
</style>
</head>
<body><main id="income-embed-root">${renderIncomeEmbed(compact)}</main>
<script nonce="__INSIGHTGINIE_EMBED_NONCE__" data-cfasync="false">${javascript}</script>
</body></html>`;
  const source = `// Generated by scripts/build-calculator-embed.mjs. Do not edit.\nexport const incomeEmbedDocuments = ${JSON.stringify({ compact: documentFor(true), full: documentFor(false) })} as const;\n`;
  await writeFile(path.join(generated, 'income-embed.ts'), source);
  console.log(
    `Built private calculator documents (${Math.round(Buffer.byteLength(source) / 1024)} KB, two views).`,
  );
} finally {
  await rm(serverPath, { force: true });
}
