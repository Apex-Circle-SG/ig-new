import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const repository = fileURLToPath(new URL('../', import.meta.url));
const generated = path.join(repository, 'apps/web/src/generated');
await mkdir(generated, { recursive: true });
const renderer = path.join(generated, '.finance-render.cjs');
const common = {
  absWorkingDir: repository,
  bundle: true,
  minify: true,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
};
const [browser] = await Promise.all([
  build({
    ...common,
    entryPoints: ['apps/web/src/finance-embed/client.tsx'],
    platform: 'browser',
    format: 'iife',
    target: ['es2022'],
    write: false,
  }),
  build({
    ...common,
    entryPoints: ['apps/web/src/finance-embed/render.tsx'],
    platform: 'node',
    format: 'cjs',
    outfile: renderer,
  }),
]);
try {
  const { FINANCE_TOOLS, renderFinanceEmbed } = createRequire(import.meta.url)(renderer);
  const css = (
    await readFile(path.join(repository, 'apps/web/src/finance-embed/embed.css'), 'utf8')
  ).replace(/<\/style/gi, '<\\/style');
  const js = browser.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  const docs = Object.fromEntries(
    FINANCE_TOOLS.map((tool) => [
      tool.id,
      `<!doctype html><html lang="en-US" data-tool="${tool.id}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="robots" content="noindex, nofollow"><meta name="referrer" content="no-referrer"><title>${tool.title} | Private InsightGinie tool</title><style>${css}</style></head><body><main id="finance-root">${renderFinanceEmbed(tool.id)}</main><script nonce="__FINANCE_EMBED_NONCE__" data-cfasync="false">${js}</script></body></html>`,
    ]),
  );
  await writeFile(
    path.join(generated, 'finance-embeds.ts'),
    `// Generated by scripts/build-finance-embeds.mjs. Do not edit.\nexport const financeEmbedDocuments = ${JSON.stringify(docs)} as const;\n`,
  );
  console.log(`Built ${FINANCE_TOOLS.length} self-contained private finance tools.`);
} finally {
  await rm(renderer, { force: true });
}
