import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';

const result = await build({
  entryPoints: ['apps/web/src/finance-embed/expanded-client.tsx'],
  bundle: true,
  minify: true,
  platform: 'browser',
  format: 'iife',
  target: 'es2022',
  define: { 'process.env.NODE_ENV': '"production"' },
  loader: { '.css': 'css' },
  outdir: 'out',
  write: false,
});
const js = result.outputFiles.find((file) => file.path.endsWith('.js')).text.replace(/<\/script/gi, '<\\/script');
const css = result.outputFiles.find((file) => file.path.endsWith('.css')).text.replace(/<\/style/gi, '<\\/style');
const html = `<!doctype html><html lang="en-US"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="robots" content="noindex, nofollow"><style>body{margin:0}${css}</style></head><body><main id="root"></main><script nonce="__NONCE__">${js}</script></body></html>`;
await mkdir('apps/web/src/generated', { recursive: true });
await writeFile('apps/web/src/generated/expanded-embed.ts', `// Generated by scripts/build-expanded-embed.mjs.\nexport const expandedEmbed = ${JSON.stringify(html)};\n`);
