import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const result = await build({
  entryPoints: ['apps/web/src/deal-embed/client.tsx'],
  bundle: true,
  minify: true,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
  platform: 'browser',
  format: 'iife',
  target: ['es2022'],
  write: false,
});
const css =
  (await readFile('apps/web/src/finance-embed/embed.css', 'utf8')) +
  (await readFile('apps/web/src/deal-embed/embed.css', 'utf8'));
const html = `<!doctype html><html lang="en-US" data-tool="__DEAL_TOOL_ID__"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="robots" content="noindex, nofollow"><meta name="referrer" content="no-referrer"><title>Private InsightGinie workspace</title><style>${css.replace(/<\/style/gi, '<\\/style')}</style></head><body><main id="deal-root">Loading private workspace…</main><script nonce="__FINANCE_EMBED_NONCE__" data-cfasync="false">${result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;
await mkdir('apps/web/src/generated', { recursive: true });
await writeFile(
  'apps/web/src/generated/deal-embed.ts',
  `// Generated by scripts/build-deal-embed.mjs.\nexport const dealEmbedDocument = ${JSON.stringify(html)};\n`,
);
console.log('Built shared private deal and market workspace.');
